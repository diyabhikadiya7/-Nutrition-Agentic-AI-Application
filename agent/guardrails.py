"""
Guardrails Module — Nutrition Agentic AI
Enforces AI ethics, safety constraints, and HAM (Helpful, Accurate, Mindful) tone.
Phase: Safety & Alignment (Agentic AI SDLC)
"""

import re
from typing import Tuple

# ── Forbidden / high-risk patterns ─────────────────────────────────────────────
HARMFUL_KEYWORDS = [
    r"\bstarve\b", r"\bextreme fast\b", r"\bcrash diet\b",
    r"\bsuicide\b", r"\bself.harm\b", r"\boverdose\b",
    r"\bpurgе\b", r"\bbinge\b",                         # eating disorder triggers
    r"\bstop.*medication\b", r"\bstop.*insulin\b",      # medication override
    r"\bcure\b.*\bdiabetes\b", r"\bcure\b.*\bcancer\b", # false cure claims
    r"\bdetox\b.*\bfast\b",
    r"\blose\s+\d{2,}\s*kg\s+in\s+\d+\s+day",          # unrealistic weight loss
]

COMPILED_HARMFUL = [re.compile(p, re.IGNORECASE) for p in HARMFUL_KEYWORDS]

# Age safety thresholds
MIN_SAFE_AGE = 5
MAX_SAFE_AGE = 110

# Maximum safe calorie deficit per day (kcal) — WHO guideline
MAX_CALORIE_DEFICIT = 1000

MEDICAL_DISCLAIMER = """
---
## ⚕️ Medical Disclaimer

> **This nutrition plan is generated by an AI system (IBM Granite) for informational and 
> educational purposes only. It does NOT constitute professional medical, dietary, or 
> clinical nutrition advice.**
>
> - Always consult a **registered dietitian (RD)** or **qualified healthcare provider** 
>   before making significant changes to your diet.
> - If you have a **chronic medical condition** (e.g., diabetes, hypertension, kidney 
>   disease, eating disorders), dietary changes must be supervised by your doctor.
> - **Emergency situations:** If you are experiencing a medical emergency, contact 
>   emergency services immediately.
> - Nutritional needs vary by individual. The plan above is a starting point — not a 
>   prescription.
>
> *Generated by Nutrition Agentic AI | Powered by IBM Granite LLM*
"""


def check_input_safety(user_input: str) -> Tuple[bool, str]:
    """
    Validates raw user input before sending to the LLM.
    Returns (is_safe: bool, reason: str).
    """
    for pattern in COMPILED_HARMFUL:
        if pattern.search(user_input):
            return False, (
                "Your message contains content that may be harmful. "
                "This application is designed to provide safe, evidence-based nutrition guidance. "
                "Please rephrase your question, or speak with a licensed healthcare professional."
            )
    return True, ""


def check_output_safety(llm_response: str) -> Tuple[bool, str]:
    """
    Post-generation output check. Flags any unsafe LLM output.
    Returns (is_safe: bool, sanitised_response: str).
    """
    for pattern in COMPILED_HARMFUL:
        if pattern.search(llm_response):
            return False, (
                "I'm sorry — part of the generated response was flagged by our safety system "
                "and cannot be displayed. Please try rephrasing your request or consult a "
                "healthcare professional for personalised advice."
            )
    return True, llm_response


def validate_age(age: int) -> Tuple[bool, str]:
    """Validates user age is within safe advisory range."""
    if not (MIN_SAFE_AGE <= age <= MAX_SAFE_AGE):
        return False, f"Age must be between {MIN_SAFE_AGE} and {MAX_SAFE_AGE} years."
    return True, ""


def validate_user_profile(profile: dict) -> Tuple[bool, str]:
    """
    Validates the complete user profile before plan generation.
    """
    required = ["name", "age", "diet_preference", "location_city", "location_country"]
    for field in required:
        if not profile.get(field, "").strip() if isinstance(profile.get(field), str) else not profile.get(field):
            return False, f"Missing required field: {field.replace('_', ' ').title()}"

    age_ok, age_msg = validate_age(int(profile["age"]))
    if not age_ok:
        return False, age_msg

    allowed_diets = {"veg", "non-veg", "vegan", "pescatarian", "flexitarian"}
    if profile.get("diet_preference", "").lower() not in allowed_diets:
        return False, "Diet preference must be one of: veg, non-veg, vegan, pescatarian, flexitarian."

    return True, ""


def append_disclaimer(plan_text: str) -> str:
    """Appends the mandatory medical disclaimer to any generated plan."""
    return plan_text + "\n" + MEDICAL_DISCLAIMER


def ham_tone_prefix() -> str:
    """Returns a HAM (Helpful, Accurate, Mindful) system tone reminder for prompts."""
    return (
        "You are a compassionate, knowledgeable nutrition assistant. "
        "Always respond in a helpful, respectful, and empathetic tone. "
        "Be accurate and evidence-based. Never make exaggerated claims. "
        "Acknowledge individual differences and always recommend professional consultation "
        "for medical conditions. Avoid any language that could trigger disordered eating."
    )
